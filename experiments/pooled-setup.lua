-- experiments/pooled-setup.lua (TSK-401 pooled leg step 1: fixture, no cleanup)
local base = debug.getinfo(1, "S").source:match("@?(.*[/\\])")
local out_path = base .. "pooled-setup.out.txt"
reaper.PreventUIRefresh(1)
local ntr0 = reaper.CountTracks(0)
reaper.InsertTrackAtIndex(ntr0, false)
local tr = reaper.GetTrack(0, ntr0)
reaper.GetSetMediaTrackInfo_String(tr, "P_NAME", "SYNTHLM-POOLED", true)
reaper.Undo_BeginBlock2(0)
local item = reaper.CreateNewMIDIItemInProj(tr, 0, 2, false)
local take = reaper.GetActiveTake(item)
reaper.MIDI_InsertNote(take, true, false, 0, 480, 0, 60, 100, false)
reaper.MIDI_InsertNote(take, true, false, 480, 960, 0, 64, 90, false)
reaper.MIDI_Sort(take)
reaper.MarkTrackItemsDirty(tr, item)
reaper.Undo_EndBlock2(0, "SYNTHLM pooled fixture", -1)
local _, guid = reaper.GetSetMediaItemTakeInfo_String(take, "GUID", "", false)
local _, buf = reaper.MIDI_GetAllEvts(take, "")
reaper.PreventUIRefresh(-1)
reaper.UpdateArrange()
local f = io.open(out_path, "w")
if f then
  f:write("track=SYNTHLM-POOLED\ntake_guid=" .. tostring(guid) .. "\nbuf_len=" .. tostring(buf and #buf or -1) .. "\n")
  f:close()
end
reaper.ShowConsoleMsg("pooled fixture ready on track SYNTHLM-POOLED\n")
