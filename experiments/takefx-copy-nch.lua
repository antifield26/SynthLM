-- experiments/takefx-copy-nch.lua (TSK-111 M3: TakeFX_CopyToTake 是否携带 NCH)
-- 运行: "C:\Program Files\REAPER (x64)\reaper.exe" -nonewinst experiments/takefx-copy-nch.lua
-- 输出: experiments/takefx-copy-nch.out.txt (分步 flush, 可重跑, 跑完删临时轨)
local base = debug.getinfo(1, "S").source:match("@?(.*[/\\])")
local out_path = base .. "takefx-copy-nch.out.txt"
local lines = {}
local function log(s) lines[#lines+1] = s end
local function flush()
  local f = io.open(out_path, "w")
  if f then f:write(table.concat(lines, "\n").."\n") f:close() end
end
local function step(name, fn)
  log("STEP|" .. name .. "|enter")
  flush()
  local r = {pcall(fn)}
  local ok = r[1]
  log("STEP|" .. name .. "|ok=" .. tostring(ok) .. (ok and "" or " err=" .. tostring(r[2]):sub(1, 200)))
  flush()
  return ok
end
local G = {}
reaper.PreventUIRefresh(1)
step("setup-track", function()
  G.ntr0 = reaper.CountTracks(0)
  reaper.InsertTrackAtIndex(G.ntr0, false)
  G.tr = reaper.GetTrack(0, G.ntr0)
  log("setup|tracks_before=" .. tostring(G.ntr0) .. " track_ok=" .. tostring(G.tr ~= nil))
end)
step("src-midi-nch8", function()
  G.src_item = reaper.CreateNewMIDIItemInProj(G.tr, 0, 2, false)
  log("src|item_ok=" .. tostring(G.src_item ~= nil))
  G.src_take = reaper.GetActiveTake(G.src_item)
  log("src|take_ok=" .. tostring(G.src_take ~= nil))
  reaper.MIDI_InsertNote(G.src_take, true, false, 0, 480, 0, 60, 100, false)
  reaper.MIDI_Sort(G.src_take)
  local fx = reaper.TakeFX_AddByName(G.src_take, "ReaEQ", -1000)
  log("src|takefx_add_neg1000=" .. tostring(fx))
  local n0 = reaper.GetMediaItemTakeInfo_Value(G.src_take, "I_TAKEFX_NCH")
  log("src|nch_before=" .. tostring(n0))
  reaper.SetMediaItemTakeInfo_Value(G.src_take, "I_TAKEFX_NCH", 8)
  local n1 = reaper.GetMediaItemTakeInfo_Value(G.src_take, "I_TAKEFX_NCH")
  log("src|nch_after8=" .. tostring(n1))
  local _, ch = reaper.GetItemStateChunk(G.src_item, "", false)
  log("src|chunk_hasNCH=" .. tostring(ch:find("TAKEFX_NCH") ~= nil))
  log("src|takefx_count=" .. tostring(reaper.TakeFX_GetCount(G.src_take)))
end)
step("dest-midi-default", function()
  G.dest_item = reaper.CreateNewMIDIItemInProj(G.tr, 5, 7, false)
  log("dest|item_ok=" .. tostring(G.dest_item ~= nil))
  G.dest_take = reaper.GetActiveTake(G.dest_item)
  log("dest|take_ok=" .. tostring(G.dest_take ~= nil))
  reaper.MIDI_InsertNote(G.dest_take, true, false, 0, 480, 0, 62, 90, false)
  reaper.MIDI_Sort(G.dest_take)
  local n = reaper.GetMediaItemTakeInfo_Value(G.dest_take, "I_TAKEFX_NCH")
  log("dest|nch_default=" .. tostring(n))
  log("dest|takefx_count_before=" .. tostring(reaper.TakeFX_GetCount(G.dest_take)))
end)
step("copy", function()
  -- dest_fx=0: 空目标追加位 (TakeFX_CopyToTake 为 void, Lua 侧返 nil, 以 count 判定)
  reaper.TakeFX_CopyToTake(G.src_take, 0, G.dest_take, 0, false)
  log("copy|dest_count_after=" .. tostring(reaper.TakeFX_GetCount(G.dest_take)))
end)
step("verify", function()
  local n = reaper.GetMediaItemTakeInfo_Value(G.dest_take, "I_TAKEFX_NCH")
  log("verify|dest_nch=" .. tostring(n))
  log("verify|dest_takefx_count=" .. tostring(reaper.TakeFX_GetCount(G.dest_take)))
  local _, ch = reaper.GetItemStateChunk(G.dest_item, "", false)
  log("verify|dest_chunk_hasNCH=" .. tostring(ch:find("TAKEFX_NCH") ~= nil))
  local carried = (tonumber(tostring(n)) == 8)
  log("verify|nch_carried=" .. tostring(carried))
  log("conclusion=" .. (carried and "TakeFX_CopyToTake 携带 NCH" or "复制后须显式回写 NCH"))
end)
step("cleanup", function()
  local tr2 = reaper.GetTrack(0, G.ntr0)
  if tr2 then reaper.DeleteTrack(tr2) log("cleanup|track_deleted=1") end
  log("cleanup|tracks_after=" .. tostring(reaper.CountTracks(0)))
end)
reaper.PreventUIRefresh(-1)
reaper.UpdateArrange()
log("done=1")
flush()
