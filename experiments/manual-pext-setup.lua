-- experiments/manual-pext-setup.lua (人工验证第 1 步：造一个带 P_EXT 的 item，不清理)
local base = debug.getinfo(1, "S").source:match("@?(.*[/\\])")
local out_path = base .. "manual-pext-setup.out.txt"
reaper.PreventUIRefresh(1)
local ntr0 = reaper.CountTracks(0)
reaper.InsertTrackAtIndex(ntr0, false)
local tr = reaper.GetTrack(0, ntr0)
reaper.GetSetMediaTrackInfo_String(tr, "P_NAME", "SYNTHLM-MANUAL", true)
reaper.Undo_BeginBlock2(0)
local item = reaper.CreateNewMIDIItemInProj(tr, 0, 2, false)
local take = reaper.GetActiveTake(item)
reaper.MIDI_InsertNote(take, true, false, 0, 480, 0, 60, 100, false)
reaper.MIDI_Sort(take)
reaper.GetSetMediaItemTakeInfo_String(take, "P_EXT:SYNTHLM_MANUAL", "hello-manual", true)
reaper.MarkTrackItemsDirty(tr, item)
reaper.Undo_EndBlock2(0, "SYNTHLM manual pext fixture", -1)
reaper.PreventUIRefresh(-1)
reaper.UpdateArrange()
local f = io.open(out_path, "w")
if f then
  f:write("fixture_track=SYNTHLM-MANUAL\nfixture_key=P_EXT:SYNTHLM_MANUAL\nfixture_val=hello-manual\n")
  f:close()
end
reaper.ShowConsoleMsg("manual fixture ready: track SYNTHLM-MANUAL\n")
